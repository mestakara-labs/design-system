// Create a separate component for the drag handle
function DragHandle({ id }: { id: number }) {
  const { attributes, listeners } = useSortable({
    id,
  });

  return (
    <Button
      {...attributes}
      {...listeners}
      variant="ghost"
      size="icon-sm"
      className="size-7 text-fg-secondary hover:bg-transparent"
    >
      <GripVertical className="size-3 text-fg-secondary" />
      <span className="sr-only">Seret untuk mengurutkan</span>
    </Button>
  );
}

